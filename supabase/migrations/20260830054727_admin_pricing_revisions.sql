create or replace function public.phase4_apply_pricing_config(
  p_revision_id uuid,
  p_config jsonb,
  p_actor_user_id uuid
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_plan jsonb;
  v_method jsonb;
  v_faq jsonb;
  v_plan_code text;
  v_mode text;
  v_duration integer;
  v_fixed_end timestamptz;
  v_plan_version_id uuid;
  v_asset_id uuid;
  v_qr_url text;
  v_amount integer;
  v_page jsonb;
  v_faqs jsonb;
begin
  if p_config is null or jsonb_typeof(p_config) <> 'object' then
    raise exception 'Pricing config must be an object';
  end if;
  if jsonb_typeof(coalesce(p_config->'page', '{}'::jsonb)) <> 'object'
     or jsonb_typeof(coalesce(p_config->'plans', '[]'::jsonb)) <> 'array'
     or jsonb_typeof(coalesce(p_config->'paymentMethods', '[]'::jsonb)) <> 'array'
     or jsonb_typeof(coalesce(p_config->'faqs', '[]'::jsonb)) <> 'array' then
    raise exception 'Pricing config sections are invalid';
  end if;
  if jsonb_array_length(coalesce(p_config->'plans', '[]'::jsonb)) not between 1 and 20
     or jsonb_array_length(coalesce(p_config->'paymentMethods', '[]'::jsonb)) > 40
     or jsonb_array_length(coalesce(p_config->'faqs', '[]'::jsonb)) > 40 then
    raise exception 'Pricing config exceeds the supported item limits';
  end if;

  v_page := coalesce(p_config->'page', '{}'::jsonb);
  if char_length(coalesce(v_page->>'eyebrow', '')) > 120
     or char_length(coalesce(v_page->>'title', '')) > 240
     or char_length(coalesce(v_page->>'intro', '')) > 2000
     or char_length(coalesce(v_page->>'notice', '')) > 2000
     or char_length(coalesce(v_page->>'finePrint', '')) > 2000 then
    raise exception 'Pricing page copy exceeds the supported length';
  end if;

  v_faqs := '[]'::jsonb;
  for v_faq in select value from jsonb_array_elements(coalesce(p_config->'faqs', '[]'::jsonb)) loop
    if jsonb_typeof(v_faq) <> 'object'
       or coalesce(v_faq->>'id', '') !~ '^[a-z0-9][a-z0-9_-]{1,63}$'
       or char_length(btrim(coalesce(v_faq->>'question', ''))) not between 2 and 300
       or char_length(btrim(coalesce(v_faq->>'answer', ''))) not between 2 and 3000 then
      raise exception 'A pricing FAQ is invalid';
    end if;
    v_faqs := v_faqs || jsonb_build_array(jsonb_build_object(
      'id', v_faq->>'id',
      'question', btrim(v_faq->>'question'),
      'answer', btrim(v_faq->>'answer'),
      'visible', coalesce((v_faq->>'visible')::boolean, true),
      'sortOrder', coalesce((v_faq->>'sortOrder')::integer, 0)
    ));
  end loop;

  delete from public.pricing_payment_channel_versions where revision_id = p_revision_id;
  delete from public.pricing_plan_versions where revision_id = p_revision_id;

  for v_plan in select value from jsonb_array_elements(p_config->'plans') loop
    v_plan_code := lower(btrim(coalesce(v_plan->>'planCode', '')));
    if v_plan_code !~ '^[a-z][a-z0-9_]{2,63}$'
       or char_length(btrim(coalesce(v_plan->>'name', ''))) not between 2 and 100
       or jsonb_typeof(coalesce(v_plan->'features', '[]'::jsonb)) <> 'array' then
      raise exception 'A pricing plan is invalid';
    end if;
    v_duration := nullif(v_plan->>'durationDays', '')::integer;
    v_mode := coalesce(nullif(v_plan->>'entitlementMode', ''),
      case when v_plan_code = 'early_access_beta' then 'fixed_end' else 'rolling_days' end);
    v_fixed_end := nullif(coalesce(
      v_plan->>'fixedEntitlementEndsAt', v_plan->>'fixedEndsAt'
    ), '')::timestamptz;
    if v_mode = 'fixed_end' and v_fixed_end is null and v_plan_code = 'early_access_beta' then
      v_fixed_end := '2026-10-01 23:59:59+08'::timestamptz;
    end if;
    if v_mode not in ('fixed_end', 'rolling_days')
       or (v_mode = 'fixed_end' and v_fixed_end is null)
       or (v_mode = 'rolling_days' and (v_duration is null or v_duration not between 1 and 366)) then
      raise exception 'A pricing plan entitlement is invalid';
    end if;
    if coalesce((v_plan->>'checkoutEnabled')::boolean, false)
       and coalesce(nullif(v_plan->>'priceCentavos', '')::integer, 0) <= 0 then
      raise exception 'A checkout-enabled pricing plan requires a positive price';
    end if;

    insert into public.plan_catalog (
      plan_code, display_name, price_php, status, description, features,
      duration_days, display_order, promotional, checkout_enabled, note,
      updated_at, updated_by
    ) values (
      v_plan_code, btrim(v_plan->>'name'),
      coalesce((v_plan->>'priceCentavos')::integer, 0) / 100.0,
      'active', coalesce(v_plan->>'description', ''),
      coalesce(v_plan->'features', '[]'::jsonb), v_duration,
      coalesce((v_plan->>'sortOrder')::integer, 0),
      coalesce((v_plan->>'promotional')::boolean, false), true,
      coalesce(v_plan->>'renewalNote', ''), clock_timestamp(), p_actor_user_id
    )
    on conflict (plan_code) do nothing;

    insert into public.pricing_plan_versions (
      revision_id, plan_code, name, badge, price_centavos, currency,
      duration_days, entitlement_mode, fixed_ends_at, description, features,
      cta_label, renewal_note, visible, display_starts_at, display_ends_at,
      checkout_enabled, checkout_starts_at, checkout_ends_at, sort_order,
      promotional, billing
    ) values (
      p_revision_id, v_plan_code, btrim(v_plan->>'name'),
      coalesce(v_plan->>'badge', ''), (v_plan->>'priceCentavos')::integer,
      coalesce(nullif(v_plan->>'currency', ''), 'PHP'),
      case when v_mode = 'rolling_days' then v_duration else null end,
      v_mode, case when v_mode = 'fixed_end' then v_fixed_end else null end,
      coalesce(v_plan->>'description', ''), coalesce(v_plan->'features', '[]'::jsonb),
      coalesce(nullif(v_plan->>'ctaLabel', ''), 'Choose plan'),
      coalesce(v_plan->>'renewalNote', ''),
      coalesce((v_plan->>'visible')::boolean, true),
      nullif(v_plan->>'displayStartsAt', '')::timestamptz,
      nullif(v_plan->>'displayEndsAt', '')::timestamptz,
      coalesce((v_plan->>'checkoutEnabled')::boolean, false),
      nullif(v_plan->>'checkoutStartsAt', '')::timestamptz,
      nullif(v_plan->>'checkoutEndsAt', '')::timestamptz,
      coalesce((v_plan->>'sortOrder')::integer, 0),
      coalesce((v_plan->>'promotional')::boolean, false), 'manual'
    );
  end loop;

  for v_method in select value from jsonb_array_elements(coalesce(p_config->'paymentMethods', '[]'::jsonb)) loop
    if coalesce(v_method->>'channelCode', '') !~ '^[a-z][a-z0-9_]{2,63}$'
       or char_length(btrim(coalesce(v_method->>'label', ''))) not between 2 and 100 then
      raise exception 'A pricing payment method is invalid';
    end if;
    v_plan_version_id := null;
    if nullif(btrim(coalesce(v_method->>'planCode', '')), '') is not null then
      select p.id into v_plan_version_id
      from public.pricing_plan_versions p
      where p.revision_id = p_revision_id
        and p.plan_code = lower(btrim(v_method->>'planCode'));
      if v_plan_version_id is null then raise exception 'Payment method plan is invalid'; end if;
    end if;

    v_asset_id := nullif(coalesce(v_method#>>'{qrAsset,assetId}', v_method->>'qrAssetId'), '')::uuid;
    if v_asset_id is not null and not exists (
      select 1 from public.pricing_assets a where a.id = v_asset_id
    ) then raise exception 'Payment method QR asset is invalid'; end if;
    v_qr_url := nullif(btrim(coalesce(v_method->>'qrUrl', '')), '');
    if v_qr_url is not null and (
      v_qr_url !~ '^/assets/payments/[A-Za-z0-9][A-Za-z0-9._-]{0,110}\.(png|jpg|jpeg)$'
      or v_qr_url like '%..%'
    ) then
      -- Dynamic asset URLs are derived from qrAsset and never trusted input.
      if v_asset_id is null or v_qr_url <> '/pricing/assets/' || v_asset_id::text then
        raise exception 'Payment method QR URL is invalid';
      end if;
      v_qr_url := null;
    end if;
    if v_asset_id is null and v_qr_url is null
       and coalesce((v_method->>'enabled')::boolean, true) then
      raise exception 'Payment method QR is required';
    end if;

    if coalesce(v_method->>'qrAmountMode', 'exact') = 'generic' then
      v_amount := null;
    elsif coalesce(v_method->>'qrAmountMode', 'exact') = 'exact' then
      v_amount := nullif(v_method->>'qrAmountCentavos', '')::integer;
      if v_amount is null then raise exception 'Exact QR amount is required'; end if;
    else
      raise exception 'Payment method QR amount mode is invalid';
    end if;

    insert into public.pricing_payment_channel_versions (
      revision_id, plan_version_id, channel_code, label, account_name,
      account_details, instructions, qr_asset_id, qr_public_path,
      amount_centavos, enabled, visible, sort_order
    ) values (
      p_revision_id, v_plan_version_id, lower(v_method->>'channelCode'),
      btrim(v_method->>'label'), coalesce(v_method->>'accountName', ''),
      coalesce(v_method->>'accountDetails', ''), coalesce(v_method->>'instructions', ''),
      v_asset_id, v_qr_url, v_amount,
      coalesce((v_method->>'enabled')::boolean, true),
      coalesce((v_method->>'visible')::boolean, true),
      coalesce((v_method->>'sortOrder')::integer, 0)
    );
  end loop;

  update public.pricing_revisions
  set page_config = jsonb_build_object('page', v_page, 'faqs', v_faqs),
      content_hash = encode(extensions.digest(p_config::text, 'sha256'), 'hex'),
      updated_at = clock_timestamp(),
      updated_by = p_actor_user_id
  where id = p_revision_id and state = 'draft';
  if not found then raise exception 'Editable pricing draft not found'; end if;
end;
$$;

create or replace function public.phase4_clone_pricing_revision(
  p_source_revision_id uuid,
  p_target_revision_id uuid
)
returns void
language plpgsql
set search_path = ''
as $$
begin
  insert into public.pricing_plan_versions (
    revision_id, plan_code, name, badge, price_centavos, currency,
    duration_days, entitlement_mode, fixed_ends_at, description, features,
    cta_label, renewal_note, visible, display_starts_at, display_ends_at,
    checkout_enabled, checkout_starts_at, checkout_ends_at, sort_order,
    promotional, billing
  )
  select p_target_revision_id, p.plan_code, p.name, p.badge, p.price_centavos,
    p.currency, p.duration_days, p.entitlement_mode, p.fixed_ends_at,
    p.description, p.features, p.cta_label, p.renewal_note, p.visible,
    p.display_starts_at, p.display_ends_at, p.checkout_enabled,
    p.checkout_starts_at, p.checkout_ends_at, p.sort_order, p.promotional, p.billing
  from public.pricing_plan_versions p
  where p.revision_id = p_source_revision_id;

  insert into public.pricing_payment_channel_versions (
    revision_id, plan_version_id, channel_code, label, account_name,
    account_details, instructions, qr_asset_id, qr_public_path,
    amount_centavos, enabled, visible, sort_order
  )
  select p_target_revision_id, target_plan.id, c.channel_code, c.label,
    c.account_name, c.account_details, c.instructions, c.qr_asset_id,
    c.qr_public_path, c.amount_centavos, c.enabled, c.visible, c.sort_order
  from public.pricing_payment_channel_versions c
  left join public.pricing_plan_versions source_plan on source_plan.id = c.plan_version_id
  left join public.pricing_plan_versions target_plan
    on target_plan.revision_id = p_target_revision_id
   and target_plan.plan_code = source_plan.plan_code
  where c.revision_id = p_source_revision_id;
end;
$$;

create or replace function public.phase4_admin_pricing_action(
  p_actor_user_id uuid,
  p_operation text,
  p_request_key text,
  p_expected_lock_version integer default null,
  p_draft_revision_id uuid default null,
  p_source_revision_id uuid default null,
  p_publish_at timestamptz default null,
  p_config jsonb default null,
  p_reason text default null,
  p_confirmed boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_operation text := lower(btrim(coalesce(p_operation, '')));
  v_reason text;
  v_inserted integer := 0;
  v_existing public.admin_action_requests%rowtype;
  v_revision public.pricing_revisions%rowtype;
  v_source public.pricing_revisions%rowtype;
  v_live_id uuid;
  v_result jsonb;
  v_event_type text;
  v_metadata jsonb := '{}'::jsonb;
  v_target_resource_id text;
begin
  perform public.phase4_require_founder(p_actor_user_id);
  if v_operation not in (
    'create_draft', 'save_draft', 'publish', 'schedule',
    'cancel_schedule', 'rollback'
  ) then raise exception 'Unsupported pricing operation'; end if;
  if p_request_key is null or p_request_key !~ '^[A-Za-z0-9_-]{16,128}$' then
    raise exception 'Valid request key required';
  end if;
  v_reason := coalesce(nullif(btrim(coalesce(p_reason, '')), ''),
    case v_operation
      when 'create_draft' then 'Founder created a pricing draft.'
      when 'save_draft' then 'Founder saved the pricing draft.'
      else null
    end);
  if char_length(coalesce(v_reason, '')) not between 5 and 1000 then
    raise exception 'A reason of 5 to 1000 characters is required';
  end if;
  if v_operation in ('publish', 'schedule', 'cancel_schedule', 'rollback')
     and not coalesce(p_confirmed, false) then
    raise exception 'Explicit confirmation is required';
  end if;
  v_target_resource_id := case when v_operation = 'rollback'
    then p_source_revision_id::text
    else coalesce(p_draft_revision_id, p_source_revision_id)::text
  end;

  insert into public.admin_action_requests (
    request_key, actor_user_id, action, target_resource_id
  ) values (
    p_request_key, p_actor_user_id, 'pricing_' || v_operation,
    v_target_resource_id
  ) on conflict (request_key) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    select * into v_existing
    from public.admin_action_requests r where r.request_key = p_request_key;
    if v_existing.actor_user_id <> p_actor_user_id
       or v_existing.action <> 'pricing_' || v_operation
       or v_existing.target_resource_id is distinct from v_target_resource_id then
      raise exception 'Request key conflict';
    end if;
    if v_existing.result is null then raise exception 'Action is already in progress'; end if;
    return v_existing.result || jsonb_build_object('replayed', true);
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('pricing-publication', 0)
  );
  perform public.phase4_promote_due_pricing_schedule(p_actor_user_id);
  v_now := clock_timestamp();
  select r.id into v_live_id
  from public.pricing_revisions r
  where r.state in ('published', 'scheduled') and r.effective_at <= v_now
  order by r.effective_at desc, r.revision_number desc limit 1;

  if v_operation = 'create_draft' then
    if exists (select 1 from public.pricing_revisions r where r.state = 'draft') then
      raise exception 'A pricing draft already exists';
    end if;
    select r.* into v_source
    from public.pricing_revisions r
    where r.id = coalesce(p_source_revision_id, v_live_id)
      and r.state in ('published', 'scheduled', 'cancelled');
    if v_source.id is null then raise exception 'Source pricing revision not found'; end if;
    insert into public.pricing_revisions (
      state, page_config, based_on_revision_id, content_hash,
      created_by, updated_by
    ) values (
      'draft', v_source.page_config, v_source.id, v_source.content_hash,
      p_actor_user_id, p_actor_user_id
    ) returning * into v_revision;
    perform public.phase4_clone_pricing_revision(v_source.id, v_revision.id);
    v_event_type := 'draft_created';
    v_metadata := jsonb_build_object('sourceRevisionId', v_source.id);

  elsif v_operation = 'save_draft' then
    if p_draft_revision_id is null or p_expected_lock_version is null then
      raise exception 'Draft revision and expected version are required';
    end if;
    select r.* into v_revision
    from public.pricing_revisions r
    where r.id = p_draft_revision_id and r.state = 'draft'
    for update;
    if v_revision.id is null then raise exception 'Pricing draft not found'; end if;
    if v_revision.lock_version <> p_expected_lock_version then
      raise exception 'Pricing draft changed; refresh before saving';
    end if;
    if p_source_revision_id is not null and p_source_revision_id <> v_live_id then
      raise exception 'Published pricing changed; refresh before saving';
    end if;
    if p_config is null then raise exception 'Pricing config is required'; end if;
    update public.pricing_revisions
    set lock_version = lock_version + 1,
        updated_at = v_now,
        updated_by = p_actor_user_id
    where id = v_revision.id and lock_version = p_expected_lock_version
    returning * into v_revision;
    if v_revision.id is null then raise exception 'Pricing draft changed; refresh before saving'; end if;
    perform public.phase4_apply_pricing_config(v_revision.id, p_config, p_actor_user_id);
    select r.* into strict v_revision from public.pricing_revisions r where r.id = v_revision.id;
    v_event_type := 'draft_saved';
    v_metadata := jsonb_build_object('previousLockVersion', p_expected_lock_version);

  elsif v_operation in ('publish', 'schedule') then
    if p_draft_revision_id is null or p_expected_lock_version is null then
      raise exception 'Draft revision and expected version are required';
    end if;
    if p_source_revision_id is null then
      raise exception 'Expected live pricing revision is required';
    end if;
    select r.* into v_revision
    from public.pricing_revisions r
    where r.id = p_draft_revision_id and r.state = 'draft'
    for update;
    if v_revision.id is null then raise exception 'Pricing draft not found'; end if;
    if v_revision.lock_version <> p_expected_lock_version then
      raise exception 'Pricing draft changed; refresh before publishing';
    end if;
    if p_source_revision_id <> v_live_id then
      raise exception 'Published pricing changed; refresh before publishing';
    end if;
    if exists (
      select 1 from public.pricing_revisions scheduled_revision
      where scheduled_revision.state = 'scheduled'
        and scheduled_revision.effective_at > v_now
    ) then
      raise exception 'Cancel the existing scheduled pricing revision before publishing or scheduling another';
    end if;
    if p_config is not null then
      perform public.phase4_apply_pricing_config(v_revision.id, p_config, p_actor_user_id);
    end if;
    if not exists (
      select 1 from public.pricing_plan_versions p
      where p.revision_id = v_revision.id and p.visible
    ) then raise exception 'At least one visible pricing plan is required'; end if;

    if v_operation = 'schedule' then
      if p_publish_at is null or p_publish_at <= v_now then
        raise exception 'Scheduled publish time must be in the future';
      end if;
      update public.pricing_revisions
      set state = 'scheduled', effective_at = p_publish_at,
          lock_version = lock_version + 1,
          updated_at = v_now, updated_by = p_actor_user_id
      where id = v_revision.id returning * into v_revision;
      v_event_type := 'scheduled';
      v_metadata := jsonb_build_object('effectiveAt', p_publish_at, 'previousLiveRevisionId', v_live_id);
    else
      update public.pricing_revisions
      set state = 'published', effective_at = v_now,
          published_at = v_now, published_by = p_actor_user_id,
          lock_version = lock_version + 1,
          updated_at = v_now, updated_by = p_actor_user_id
      where id = v_revision.id returning * into v_revision;
      v_event_type := 'published';
      v_metadata := jsonb_build_object('previousLiveRevisionId', v_live_id);
    end if;

  elsif v_operation = 'cancel_schedule' then
    if p_source_revision_id is null or p_expected_lock_version is null then
      raise exception 'Scheduled revision and expected version are required';
    end if;
    select r.* into v_revision
    from public.pricing_revisions r
    where r.id = p_source_revision_id and r.state = 'scheduled'
      and r.effective_at > v_now
    for update;
    if v_revision.id is null then raise exception 'Scheduled pricing revision not found'; end if;
    if v_revision.lock_version <> p_expected_lock_version then
      raise exception 'Scheduled pricing revision changed; refresh before cancelling';
    end if;
    update public.pricing_revisions
    set state = 'cancelled', cancelled_at = v_now,
        cancelled_by = p_actor_user_id, lock_version = lock_version + 1,
        updated_at = v_now, updated_by = p_actor_user_id
    where id = v_revision.id returning * into v_revision;
    v_event_type := 'schedule_cancelled';
    v_metadata := jsonb_build_object('scheduledEffectiveAt', v_revision.effective_at);

  else
    if p_source_revision_id is null then raise exception 'Rollback source revision is required'; end if;
    -- Rollback has no editable draft. Its otherwise-unused draft-id slot carries
    -- the live revision the Founder previewed, preserving the fixed RPC shape
    -- while preventing a stale tab from overwriting a newer publication.
    if p_draft_revision_id is null then
      raise exception 'Expected live pricing revision is required for rollback';
    end if;
    if p_draft_revision_id <> v_live_id then
      raise exception 'Published pricing changed; refresh before rollback';
    end if;
    if exists (select 1 from public.pricing_revisions r where r.state = 'draft') then
      raise exception 'Publish or discard the existing draft before rollback';
    end if;
    if exists (
      select 1 from public.pricing_revisions scheduled_revision
      where scheduled_revision.state = 'scheduled'
        and scheduled_revision.effective_at > v_now
    ) then
      raise exception 'Cancel the scheduled pricing revision before rollback';
    end if;
    select r.* into v_source
    from public.pricing_revisions r
    where r.id = p_source_revision_id
      and r.state in ('published', 'scheduled', 'cancelled');
    if v_source.id is null then raise exception 'Rollback source revision not found'; end if;
    insert into public.pricing_revisions (
      state, page_config, based_on_revision_id, rollback_of_revision_id,
      content_hash, created_by, updated_by
    ) values (
      'draft', v_source.page_config, v_live_id, v_source.id,
      v_source.content_hash, p_actor_user_id, p_actor_user_id
    ) returning * into v_revision;
    perform public.phase4_clone_pricing_revision(v_source.id, v_revision.id);
    update public.pricing_revisions
    set state = 'published', effective_at = v_now,
        published_at = v_now, published_by = p_actor_user_id,
        lock_version = lock_version + 1,
        updated_at = v_now, updated_by = p_actor_user_id
    where id = v_revision.id returning * into v_revision;
    v_event_type := 'rollback_published';
    v_metadata := jsonb_build_object(
      'rollbackOfRevisionId', v_source.id,
      'previousLiveRevisionId', v_live_id
    );
  end if;

  v_result := jsonb_build_object(
    'ok', true,
    'operation', v_operation,
    'requestKey', p_request_key,
    'replayed', false,
    'revisionId', v_revision.id,
    'state', v_revision.state,
    'lockVersion', v_revision.lock_version,
    'effectiveAt', v_revision.effective_at,
    'snapshot', public.phase4_pricing_revision_snapshot(v_revision.id, false, v_now)
  );

  insert into public.pricing_publication_events (
    revision_id, actor_user_id, event_type, request_key, reason, metadata, result
  ) values (
    v_revision.id, p_actor_user_id, v_event_type, p_request_key,
    v_reason, v_metadata, v_result
  );
  insert into public.admin_audit_log (
    actor_user_id, action_type, target_resource_type, target_resource_id,
    reason, details
  ) values (
    p_actor_user_id, 'content_management_action', 'pricing_revision',
    v_revision.id::text, v_reason,
    jsonb_build_object(
      'requestKey', p_request_key,
      'operation', v_operation,
      'revisionId', v_revision.id,
      'state', v_revision.state
    )
  );
  update public.admin_action_requests
  set result = v_result, completed_at = v_now
  where request_key = p_request_key;
  return v_result;
end;
$$;

