import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = 'https://raw.githubusercontent.com/notofonts/noto-fonts/ffebf8c1ee449e544955a7e813c54f9b73848eac/hinted/ttf/NotoSans/NotoSans-Regular.ttf';
const expectedSha256 = 'b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5';
const target = path.join(root, 'worker', 'noto-sans-latin-ext.mjs');
const response = await fetch(source);
if (!response.ok) throw new Error(`Unable to download pinned Noto Sans font (${response.status}).`);
const bytes = Buffer.from(await response.arrayBuffer());
const sha256 = createHash('sha256').update(bytes).digest('hex');
if (sha256 !== expectedSha256) throw new Error('Pinned Noto Sans font checksum mismatch.');
const base64 = bytes.toString('base64');
const lines = base64.match(/.{1,100}/g) || [];
const moduleSource = [
  '// Generated by scripts/build-worker-font-module.mjs from the pinned official Noto Sans TTF.',
  '// Noto Sans is licensed under the SIL Open Font License 1.1.',
  'export default [',
  ...lines.map((line) => `  '${line}',`),
  "].join('');",
  '',
].join('\n');
await writeFile(target, moduleSource, 'utf8');
console.log(`Generated ${path.relative(root, target)} (${bytes.length} font bytes).`);
