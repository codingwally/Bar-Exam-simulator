create or replace function public.phase4_admin_register_pricing_asset(
  p_actor_user_id uuid,
  p_request_key text,
  p_bucket_id text,
  p_object_path text,
  p_mime_type text,
  p_size_bytes bigint,
  p_width integer,
  p_height integer,
  p_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_inserted integer := 0;
  v_existing public.admin_action_requests%rowtype;
  v_asset public.pricing_assets%rowtype;
  v_result jsonb;
begin
  perform public.phase4_require_founder(p_actor_user_id);
  if p_request_key is null or p_request_key !~ '^[A-Za-z0-9_-]{16,128}$' then
    raise exception 'Valid request key required';
  end if;
  if p_bucket_id <> 'pricing-assets'
     or p_object_path !~ '^[0-9a-z][0-9A-Za-z._/-]{2,239}$'
     or p_object_path like '/%'
     or p_object_path like '%..%'
     or p_object_path like '%//%'
     or p_mime_type not in ('image/png', 'image/jpeg')
     or p_size_bytes not between 1 and 5242880
     or p_width not between 100 and 4096
     or p_height not between 100 and 4096
     or lower(coalesce(p_sha256, '')) !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid pricing QR asset metadata';
  end if;

  insert into public.admin_action_requests (
    request_key, actor_user_id, action, target_resource_id
  ) values (
    p_request_key, p_actor_user_id, 'pricing_asset_register', p_object_path
  ) on conflict (request_key) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    select * into v_existing from public.admin_action_requests where request_key = p_request_key;
    if v_existing.actor_user_id <> p_actor_user_id
       or v_existing.action <> 'pricing_asset_register'
       or v_existing.target_resource_id <> p_object_path then
      raise exception 'Request key conflict';
    end if;
    if v_existing.result is null then raise exception 'Action is already in progress'; end if;
    return v_existing.result || jsonb_build_object('replayed', true);
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('pricing-asset:' || p_bucket_id || ':' || p_object_path, 0)
  );
  select a.* into v_asset
  from public.pricing_assets a
  where a.bucket_id = p_bucket_id and a.object_path = p_object_path;
  if v_asset.id is not null then
    if v_asset.mime_type <> p_mime_type
       or v_asset.size_bytes <> p_size_bytes
       or v_asset.width <> p_width
       or v_asset.height <> p_height
       or v_asset.sha256 <> lower(p_sha256) then
      raise exception 'Pricing asset path is already registered with different metadata';
    end if;
  else
    insert into public.pricing_assets (
      bucket_id, object_path, mime_type, size_bytes, width, height,
      sha256, created_by
    ) values (
      p_bucket_id, p_object_path, p_mime_type, p_size_bytes, p_width,
      p_height, lower(p_sha256), p_actor_user_id
    ) returning * into v_asset;
  end if;

  v_result := jsonb_build_object(
    'assetId', v_asset.id,
    'bucketId', v_asset.bucket_id,
    'objectPath', v_asset.object_path,
    'mimeType', v_asset.mime_type,
    'sizeBytes', v_asset.size_bytes,
    'width', v_asset.width,
    'height', v_asset.height,
    'sha256', v_asset.sha256,
    'replayed', false
  );
  insert into public.pricing_publication_events (
    revision_id, actor_user_id, event_type, request_key, reason, metadata, result
  ) values (
    null, p_actor_user_id, 'asset_registered', p_request_key,
    'Founder registered a pricing QR asset.',
    jsonb_build_object('assetId', v_asset.id), v_result
  );
  insert into public.admin_audit_log (
    actor_user_id, action_type, target_resource_type, target_resource_id,
    reason, details
  ) values (
    p_actor_user_id, 'content_management_action', 'pricing_asset',
    v_asset.id::text, 'Founder registered a pricing QR asset.',
    jsonb_build_object('requestKey', p_request_key, 'sha256', v_asset.sha256)
  );
  update public.admin_action_requests
  set result = v_result, completed_at = v_now
  where request_key = p_request_key;
  return v_result;
end;
$$;

