create or replace function public.phase4_pricing_public_asset(p_asset_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_asset public.pricing_assets%rowtype;
begin
  select a.* into v_asset
  from public.pricing_assets a
  where a.id = p_asset_id
    and exists (
      select 1
      from public.pricing_payment_channel_versions c
      join public.pricing_revisions r on r.id = c.revision_id
      where c.qr_asset_id = a.id
        and c.enabled and c.visible
        and r.id = (
          select live.id
          from public.pricing_revisions live
          where live.state in ('published', 'scheduled')
            and live.effective_at <= v_now
          order by live.effective_at desc, live.revision_number desc limit 1
        )
        and exists (
          select 1
          from public.pricing_plan_versions p
          where p.revision_id = r.id
            and p.visible
            and (p.display_starts_at is null or v_now >= p.display_starts_at)
            and (p.display_ends_at is null or v_now < p.display_ends_at)
            and (c.plan_version_id is null or c.plan_version_id = p.id)
            and (c.amount_centavos is null or c.amount_centavos = p.price_centavos)
        )
    );
  if v_asset.id is null then return null; end if;
  return jsonb_build_object(
    'assetId', v_asset.id, 'bucketId', v_asset.bucket_id,
    'objectPath', v_asset.object_path, 'mimeType', v_asset.mime_type,
    'sizeBytes', v_asset.size_bytes, 'width', v_asset.width,
    'height', v_asset.height, 'sha256', v_asset.sha256
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Trusted versioned checkout and compatibility closure
-- ---------------------------------------------------------------------------

create or replace function public.phase4_create_payment_request_v2(
  p_user_id uuid,
  p_plan_version_id uuid,
  p_payment_channel_version_id uuid,
  p_payment_date date,
  p_payment_reference text,
  p_proof_bucket text,
  p_proof_path text,
  p_proof_mime_type text,
  p_proof_size_bytes bigint,
  p_proof_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_ph_date date := (clock_timestamp() at time zone 'Asia/Manila')::date;
  v_revision public.pricing_revisions%rowtype;
  v_plan public.pricing_plan_versions%rowtype;
  v_channel public.pricing_payment_channel_versions%rowtype;
  v_request public.payment_requests%rowtype;
  v_request_key text;
  v_prior_provisional boolean := false;
begin
  if p_user_id is null or not exists (
    select 1 from auth.users u
    where u.id = p_user_id and coalesce(u.is_anonymous, false) = false
  ) then raise exception 'Authenticated user required'; end if;
  if p_plan_version_id is null or p_payment_channel_version_id is null then
    raise exception 'Plan and payment method are required';
  end if;

  -- Resolve an already accepted retry before consulting today's live revision.
  -- Otherwise a response lost just before a pricing publication would become
  -- unrecoverable as soon as the submitted plan version turns stale.
  v_request_key := 'pricingv2_' || substr(encode(extensions.digest(
    p_user_id::text || '|' || p_plan_version_id::text || '|'
      || p_payment_channel_version_id::text || '|'
      || lower(btrim(p_payment_reference)) || '|' || lower(p_proof_sha256),
    'sha256'
  ), 'hex'), 1, 54);

  select r.* into v_request
  from public.payment_requests r where r.request_key = v_request_key;
  if v_request.id is not null then
    if v_request.user_id <> p_user_id
       or v_request.pricing_plan_version_id <> p_plan_version_id
       or v_request.pricing_payment_channel_version_id <> p_payment_channel_version_id then
      raise exception 'Payment request key conflict';
    end if;
    return jsonb_build_object(
      'id', v_request.id, 'status', v_request.status,
      'pricingRevisionId', v_request.pricing_revision_id,
      'planVersionId', v_request.pricing_plan_version_id,
      'paymentChannelVersionId', v_request.pricing_payment_channel_version_id,
      'planCode', v_request.plan_code, 'planName', v_request.trusted_plan_name,
      'amountPhp', v_request.trusted_amount_php,
      'amountCentavos', v_request.trusted_amount_centavos,
      'currency', v_request.trusted_currency,
      'durationDays', v_request.trusted_duration_days,
      'entitlementMode', v_request.trusted_entitlement_mode,
      'fixedEndsAt', v_request.trusted_fixed_ends_at,
      'submittedAt', v_request.submitted_at,
      'proofObjectPath', v_request.proof_object_path,
      'provisionalAccessExpiresAt', v_request.provisional_access_expires_at,
      'provisionalGrantReused', v_request.provisional_access_started_at is null,
      'replayed', true
    );
  end if;

  select r.* into v_revision
  from public.pricing_revisions r
  where r.state in ('published', 'scheduled')
    and r.effective_at <= v_now
  order by r.effective_at desc, r.revision_number desc limit 1;
  select p.* into v_plan
  from public.pricing_plan_versions p
  where p.id = p_plan_version_id and p.revision_id = v_revision.id;
  if v_plan.id is null
     or not v_plan.visible
     or (v_plan.display_starts_at is not null and v_now < v_plan.display_starts_at)
     or (v_plan.display_ends_at is not null and v_now >= v_plan.display_ends_at)
     or not v_plan.checkout_enabled
     or (v_plan.checkout_starts_at is not null and v_now < v_plan.checkout_starts_at)
     or (v_plan.checkout_ends_at is not null and v_now >= v_plan.checkout_ends_at) then
    raise exception 'Selected pricing plan is not open for checkout';
  end if;
  select c.* into v_channel
  from public.pricing_payment_channel_versions c
  where c.id = p_payment_channel_version_id
    and c.revision_id = v_revision.id
    and c.enabled and c.visible
    and (c.qr_asset_id is not null or c.qr_public_path is not null)
    and (c.plan_version_id is null or c.plan_version_id = v_plan.id)
    and (c.amount_centavos is null or c.amount_centavos = v_plan.price_centavos);
  if v_channel.id is null then
    raise exception 'Payment method is not compatible with the selected plan amount';
  end if;

  if p_payment_date is null
     or p_payment_date < v_ph_date - 31
     or p_payment_date > v_ph_date + 1 then
    raise exception 'Payment date is outside the accepted range';
  end if;
  if char_length(btrim(coalesce(p_payment_reference, ''))) not between 4 and 100 then
    raise exception 'Payment reference is invalid';
  end if;
  if p_proof_bucket <> 'payment-proofs'
     or p_proof_path !~ '^[0-9a-f-]{36}/[0-9a-f-]{36}\.(png|jpg|pdf)$'
     or p_proof_mime_type not in ('image/png', 'image/jpeg', 'application/pdf')
     or p_proof_size_bytes not between 1 and 6291456
     or lower(coalesce(p_proof_sha256, '')) !~ '^[0-9a-f]{64}$' then
    raise exception 'Payment proof metadata is invalid';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('payment:' || p_user_id::text, 0)
  );
  -- A concurrent retry can pass the optimistic lookup before the first
  -- transaction commits. Recheck under the per-user lock so it receives the
  -- same authoritative payment instead of a spurious "awaiting review" error.
  select r.* into v_request
  from public.payment_requests r where r.request_key = v_request_key;
  if v_request.id is not null then
    if v_request.user_id <> p_user_id
       or v_request.pricing_plan_version_id <> p_plan_version_id
       or v_request.pricing_payment_channel_version_id <> p_payment_channel_version_id then
      raise exception 'Payment request key conflict';
    end if;
    return jsonb_build_object(
      'id', v_request.id, 'status', v_request.status,
      'pricingRevisionId', v_request.pricing_revision_id,
      'planVersionId', v_request.pricing_plan_version_id,
      'paymentChannelVersionId', v_request.pricing_payment_channel_version_id,
      'planCode', v_request.plan_code, 'planName', v_request.trusted_plan_name,
      'amountPhp', v_request.trusted_amount_php,
      'amountCentavos', v_request.trusted_amount_centavos,
      'currency', v_request.trusted_currency,
      'durationDays', v_request.trusted_duration_days,
      'entitlementMode', v_request.trusted_entitlement_mode,
      'fixedEndsAt', v_request.trusted_fixed_ends_at,
      'submittedAt', v_request.submitted_at,
      'proofObjectPath', v_request.proof_object_path,
      'provisionalAccessExpiresAt', v_request.provisional_access_expires_at,
      'provisionalGrantReused', v_request.provisional_access_started_at is null,
      'replayed', true
    );
  end if;
  if exists (
    select 1 from public.payment_requests r
    where r.user_id = p_user_id and r.status in ('pending', 'needs_information')
  ) then raise exception 'A payment request is already awaiting review'; end if;
  select exists (
    select 1 from public.payment_requests r
    where r.user_id = p_user_id and r.provisional_access_started_at is not null
  ) or exists (
    select 1 from public.subscriptions s
    where s.user_id = p_user_id
      and s.source in ('manual_payment', 'admin_adjustment', 'migration')
  ) into v_prior_provisional;

  insert into public.payment_requests (
    user_id, plan_code, trusted_amount_php, payment_method, payment_date,
    transaction_reference, student_note, proof_bucket, proof_object_path,
    proof_original_name, proof_mime_type, proof_size_bytes, proof_sha256,
    request_key, provisional_access_started_at, provisional_access_expires_at,
    pricing_revision_id, pricing_plan_version_id,
    pricing_payment_channel_version_id, trusted_plan_name,
    trusted_amount_centavos, trusted_currency, trusted_duration_days,
    trusted_entitlement_mode, trusted_fixed_ends_at,
    trusted_payment_channel_label, trusted_payment_account_details
  ) values (
    p_user_id, v_plan.plan_code, v_plan.price_centavos / 100.0,
    v_channel.channel_code, p_payment_date, btrim(p_payment_reference), null,
    p_proof_bucket, p_proof_path,
    left(pg_catalog.regexp_replace(p_proof_path, '^.*/', ''), 180),
    p_proof_mime_type, p_proof_size_bytes::integer,
    lower(p_proof_sha256), v_request_key,
    case when v_prior_provisional then null else v_now end,
    case when v_prior_provisional then null else v_now + interval '24 hours' end,
    v_revision.id, v_plan.id, v_channel.id, v_plan.name,
    v_plan.price_centavos, v_plan.currency, v_plan.duration_days,
    v_plan.entitlement_mode, v_plan.fixed_ends_at, v_channel.label,
    v_channel.account_details
  ) returning * into v_request;

  insert into public.payment_request_history (
    payment_request_id, actor_user_id, action, previous_status, new_status,
    reason, request_key, metadata
  ) values (
    v_request.id, p_user_id, 'submitted', null, 'pending',
    'Student submitted a versioned plan payment for manual verification.',
    left(v_request_key, 96) || '_history',
    jsonb_build_object(
      'pricingRevisionId', v_revision.id,
      'planVersionId', v_plan.id,
      'paymentChannelVersionId', v_channel.id,
      'amountCentavos', v_plan.price_centavos,
      'provisionalAccessExpiresAt', v_request.provisional_access_expires_at
    )
  );
  insert into public.outbound_notifications (
    notification_type, recipient_mailbox, subject, secure_admin_path,
    related_resource_type, related_resource_id
  ) values (
    'payment_submitted', 'premium@duediligence.ph',
    'Due Diligence plan payment verification request',
    '/admin/payments?request=' || v_request.id::text,
    'payment_request', v_request.id
  );

  return jsonb_build_object(
    'id', v_request.id, 'status', v_request.status,
    'pricingRevisionId', v_revision.id,
    'planVersionId', v_plan.id,
    'paymentChannelVersionId', v_channel.id,
    'planCode', v_plan.plan_code, 'planName', v_plan.name,
    'amountPhp', v_request.trusted_amount_php,
    'amountCentavos', v_plan.price_centavos,
    'currency', v_plan.currency, 'durationDays', v_plan.duration_days,
    'entitlementMode', v_plan.entitlement_mode,
    'fixedEndsAt', v_plan.fixed_ends_at,
    'submittedAt', v_request.submitted_at,
    'proofObjectPath', v_request.proof_object_path,
    'provisionalAccessExpiresAt', v_request.provisional_access_expires_at,
    'provisionalGrantReused', v_prior_provisional,
    'replayed', false
  );
exception
  when unique_violation then
    if exists (
      select 1 from public.payment_requests r
      where r.payment_method = v_channel.channel_code
        and r.reference_normalized = lower(btrim(p_payment_reference))
    ) then
      raise exception 'This transaction reference has already been submitted for this payment channel';
    end if;
    raise;
end;
$$;

-- Stale clients can use this signature only before the exact legacy cutoff.
create or replace function public.phase4_create_payment_request(
  p_user_id uuid,
  p_plan_code text,
  p_amount_php numeric,
  p_payment_method text,
  p_payment_date date,
  p_transaction_reference text,
  p_student_note text,
  p_proof_object_path text,
  p_proof_original_name text,
  p_proof_mime_type text,
  p_proof_size_bytes integer,
  p_proof_sha256 text,
  p_request_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_existing public.payment_requests%rowtype;
  v_plan_id uuid;
  v_channel_id uuid;
  v_result jsonb;
begin
  if p_request_key is null or p_request_key !~ '^[A-Za-z0-9_-]{16,128}$' then
    raise exception 'Valid request key required';
  end if;
  if lower(btrim(coalesce(p_plan_code, ''))) <> 'early_access_beta'
     or round(coalesce(p_amount_php, 0), 2) <> 149.00 then
    raise exception 'Only the legacy 149-peso Early Access offer is available through this checkout';
  end if;
  -- Recover a response lost at the cutoff before refusing genuinely new legacy
  -- submissions. The compatibility wrapper stores a v2-derived request key,
  -- so bind the retry to the complete immutable proof/reference identity.
  select r.* into v_existing
  from public.payment_requests r
  where r.user_id = p_user_id
    and r.pricing_plan_version_id is not null
    and r.plan_code = 'early_access_beta'
    and r.trusted_amount_centavos = 14900
    and r.payment_method = lower(btrim(coalesce(p_payment_method, '')))
    and r.reference_normalized = lower(btrim(coalesce(p_transaction_reference, '')))
    and r.proof_sha256 = lower(coalesce(p_proof_sha256, ''))
    and r.submitted_at < '2026-09-01 00:00:00+08'::timestamptz
  order by r.submitted_at desc
  limit 1;
  if v_existing.id is not null then
    return jsonb_build_object(
      'id', v_existing.id, 'status', v_existing.status,
      'pricingRevisionId', v_existing.pricing_revision_id,
      'planVersionId', v_existing.pricing_plan_version_id,
      'paymentChannelVersionId', v_existing.pricing_payment_channel_version_id,
      'planCode', v_existing.plan_code, 'planName', v_existing.trusted_plan_name,
      'amountPhp', v_existing.trusted_amount_php,
      'amountCentavos', v_existing.trusted_amount_centavos,
      'currency', v_existing.trusted_currency,
      'durationDays', v_existing.trusted_duration_days,
      'entitlementMode', v_existing.trusted_entitlement_mode,
      'fixedEndsAt', v_existing.trusted_fixed_ends_at,
      'submittedAt', v_existing.submitted_at,
      'proofObjectPath', v_existing.proof_object_path,
      'provisionalAccessExpiresAt', v_existing.provisional_access_expires_at,
      'provisionalGrantReused', v_existing.provisional_access_started_at is null,
      'replayed', true
    );
  end if;
  if v_now >= '2026-09-01 00:00:00+08'::timestamptz then
    raise exception 'Early Access checkout is closed; refresh Plans & Pricing';
  end if;

  select p.id, c.id into v_plan_id, v_channel_id
  from public.pricing_revisions r
  join public.pricing_plan_versions p on p.revision_id = r.id
  join public.pricing_payment_channel_versions c on c.revision_id = r.id
    and (c.plan_version_id is null or c.plan_version_id = p.id)
  where r.id = (
      select live.id
      from public.pricing_revisions live
      where live.state in ('published', 'scheduled')
        and live.effective_at <= v_now
      order by live.effective_at desc, live.revision_number desc limit 1
    )
    and p.plan_code = 'early_access_beta'
    and p.price_centavos = 14900
    and p.checkout_enabled
    and (p.checkout_starts_at is null or v_now >= p.checkout_starts_at)
    and (p.checkout_ends_at is null or v_now < p.checkout_ends_at)
    and c.channel_code = lower(btrim(coalesce(p_payment_method, '')))
    and c.enabled and c.visible
    and (c.qr_asset_id is not null or c.qr_public_path is not null)
    and (c.amount_centavos is null or c.amount_centavos = 14900)
  order by c.sort_order limit 1;
  if v_plan_id is null or v_channel_id is null then
    raise exception 'Legacy payment method is unavailable';
  end if;

  v_result := public.phase4_create_payment_request_v2(
    p_user_id, v_plan_id, v_channel_id, p_payment_date,
    p_transaction_reference, 'payment-proofs', p_proof_object_path,
    p_proof_mime_type, p_proof_size_bytes, p_proof_sha256
  );
  if coalesce((v_result->>'replayed')::boolean, false) = false then
    update public.payment_requests
    set student_note = nullif(btrim(coalesce(p_student_note, '')), ''),
        proof_original_name = left(coalesce(nullif(btrim(p_proof_original_name), ''), proof_original_name), 180)
    where id = (v_result->>'id')::uuid;
  end if;
  return v_result;
end;
$$;

-- Live access validates captured immutable provenance, never the mutable
-- checkout flag. This is what makes delayed legacy approvals safe.
create or replace function public.phase4_enforce_live_subscription_plan()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status in ('trialing', 'pending_payment', 'active', 'paused') then
    if new.pricing_plan_version_id is not null then
      if not exists (
        select 1
        from public.pricing_plan_versions p
        join public.pricing_revisions r on r.id = p.revision_id
        where p.id = new.pricing_plan_version_id
          and p.revision_id = new.pricing_revision_id
          and p.plan_code = new.plan_code
          and r.state in ('published', 'scheduled')
          and p.entitlement_mode = new.entitlement_mode
          and (
            p.entitlement_mode = 'fixed_end'
            or p.duration_days = new.term_duration_days
          )
      ) then
        raise exception 'Captured pricing provenance is invalid for live access';
      end if;
    elsif not exists (
      select 1 from public.plan_catalog p
      where p.plan_code = new.plan_code
        and p.status = 'active'
        and (p.duration_days is not null or new.expires_at is not null)
    ) then
      raise exception 'Selected plan is not available for live subscription access';
    end if;
  end if;
  return new;
end;
$$;

create or replace function public.phase4_admin_review_payment(
  p_actor_user_id uuid,
  p_payment_request_id uuid,
  p_payload jsonb,
  p_reason text,
  p_request_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_inserted integer := 0;
  v_existing_action public.admin_action_requests%rowtype;
  v_payment public.payment_requests%rowtype;
  v_plan public.pricing_plan_versions%rowtype;
  v_subscription public.subscriptions%rowtype;
  v_status text;
  v_mode text;
  v_duration integer;
  v_fixed_end timestamptz;
  v_expires_at timestamptz;
  v_base timestamptz;
  v_purchased_start timestamptz;
  v_purchased_end timestamptz;
  v_prior_expiry timestamptz;
  v_entitlement_changed boolean := false;
  v_previous_payment jsonb;
  v_previous_subscription jsonb := '{}'::jsonb;
  v_prior_subscription_snapshot jsonb;
  v_history_action text := 'activate';
  v_result jsonb;
begin
  perform public.phase4_require_founder(p_actor_user_id);
  if char_length(btrim(coalesce(p_reason, ''))) not between 5 and 1000
     or p_request_key is null
     or p_request_key !~ '^[A-Za-z0-9_-]{16,128}$' then
    raise exception 'Valid review reason and request key required';
  end if;

  insert into public.admin_action_requests (
    request_key, actor_user_id, action, target_resource_id
  ) values (
    p_request_key, p_actor_user_id, 'payment_review', p_payment_request_id::text
  ) on conflict (request_key) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    select * into v_existing_action
    from public.admin_action_requests r where r.request_key = p_request_key;
    if v_existing_action.actor_user_id <> p_actor_user_id
       or v_existing_action.action <> 'payment_review'
       or v_existing_action.target_resource_id <> p_payment_request_id::text then
      raise exception 'Request key conflict';
    end if;
    if v_existing_action.result is null then raise exception 'Action is already in progress'; end if;
    return v_existing_action.result || jsonb_build_object('replayed', true);
  end if;

  select r.* into v_payment
  from public.payment_requests r
  where r.id = p_payment_request_id for update;
  if v_payment.id is null then raise exception 'Payment request not found'; end if;
  v_status := lower(btrim(coalesce(p_payload->>'status', '')));
  if v_status not in ('needs_information', 'approved', 'rejected')
     or v_payment.status not in ('pending', 'needs_information') then
    raise exception 'Payment request is no longer reviewable';
  end if;
  v_previous_payment := to_jsonb(v_payment) - array[
    'student_note', 'proof_object_path', 'proof_original_name', 'proof_sha256',
    'trusted_payment_account_details'
  ];

  if v_status = 'approved' then
    if v_payment.pricing_plan_version_id is not null then
      select p.* into v_plan
      from public.pricing_plan_versions p
      where p.id = v_payment.pricing_plan_version_id
        and p.revision_id = v_payment.pricing_revision_id
        and p.plan_code = v_payment.plan_code;
      if v_plan.id is null
         or v_payment.trusted_amount_centavos <> v_plan.price_centavos
         or v_payment.trusted_amount_php <> v_plan.price_centavos / 100.0
         or v_payment.trusted_plan_name <> v_plan.name
         or v_payment.trusted_currency <> v_plan.currency
         or v_payment.trusted_entitlement_mode <> v_plan.entitlement_mode
         or v_payment.trusted_duration_days is distinct from v_plan.duration_days
         or v_payment.trusted_fixed_ends_at is distinct from v_plan.fixed_ends_at then
        raise exception 'Captured payment plan snapshot does not match immutable pricing evidence';
      end if;
    elsif v_payment.plan_code = 'early_access_beta'
       and v_payment.trusted_amount_php = 149.00
       and v_payment.submitted_at < '2026-09-01 00:00:00+08'::timestamptz then
      select p.* into v_plan
      from public.pricing_plan_versions p
      where p.id = 'a8300000-0000-4000-8000-000000000101'::uuid;
      if v_plan.id is null then raise exception 'Legacy pricing evidence is unavailable'; end if;
    else
      raise exception 'Trusted payment plan evidence cannot be activated';
    end if;

    v_mode := v_plan.entitlement_mode;
    v_duration := v_plan.duration_days;
    v_fixed_end := v_plan.fixed_ends_at;
    if v_mode = 'fixed_end' and (v_fixed_end is null or v_fixed_end <= v_now) then
      raise exception 'The fixed legacy entitlement has ended';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(
      pg_catalog.hashtextextended('subscription:' || v_payment.user_id::text, 0)
    );
    select s.* into v_subscription
    from public.subscriptions s
    where s.user_id = v_payment.user_id
      and s.status in ('trialing', 'pending_payment', 'active', 'paused')
    order by s.expires_at desc nulls first, s.updated_at desc
    limit 1 for update;

    if v_subscription.id is not null then
      -- Server-created allowlist only: bounded evidence sufficient to restore
      -- the exact prior entitlement without persisting the whole table row.
      v_prior_subscription_snapshot := jsonb_build_object(
        'snapshotVersion', 1,
        'subscriptionId', v_subscription.id,
        'planCode', v_subscription.plan_code,
        'status', v_subscription.status,
        'startsAt', v_subscription.starts_at,
        'expiresAt', v_subscription.expires_at,
        'source', v_subscription.source,
        'pricingRevisionId', v_subscription.pricing_revision_id,
        'pricingPlanVersionId', v_subscription.pricing_plan_version_id,
        'termDurationDays', v_subscription.term_duration_days,
        'entitlementMode', v_subscription.entitlement_mode
      );
    end if;

    if v_mode = 'rolling_days' and v_subscription.id is not null
       and v_subscription.expires_at is null then
      -- A paid approval may link to a stronger non-expiring entitlement, but
      -- it must never replace that entitlement with a shorter 30-day term.
      v_history_action := null;
      v_entitlement_changed := false;

    elsif v_mode = 'rolling_days' and v_subscription.id is not null
       and v_subscription.expires_at is not null then
      -- Paid days begin after any later finite live entitlement, including a
      -- complimentary grant. The prior expiry and complete previous row are
      -- retained below for audit and exact-segment refund reversal.
      v_previous_subscription := to_jsonb(v_subscription);
      v_prior_expiry := v_subscription.expires_at;
      v_base := greatest(v_now, coalesce(v_subscription.expires_at, v_now));
      v_expires_at := v_base + pg_catalog.make_interval(days => v_duration);
      v_purchased_start := v_base;
      v_purchased_end := v_expires_at;
      v_entitlement_changed := true;
      v_history_action := case when v_subscription.plan_code = v_plan.plan_code
        then 'extend' else 'replace_plan' end;
      update public.subscriptions
      set plan_code = v_plan.plan_code,
          status = 'active',
          starts_at = coalesce(starts_at, v_now),
          expires_at = v_expires_at,
          source = 'manual_payment',
          updated_at = v_now,
          updated_by = p_actor_user_id,
          reason = btrim(p_reason),
          version = version + 1,
          pricing_revision_id = v_plan.revision_id,
          pricing_plan_version_id = v_plan.id,
          term_duration_days = v_plan.duration_days,
          entitlement_mode = v_plan.entitlement_mode
      where id = v_subscription.id returning * into v_subscription;

    elsif v_mode = 'fixed_end'
       and v_subscription.id is not null
       and (v_subscription.expires_at is null or v_subscription.expires_at >= v_fixed_end) then
      -- Link the approval without shortening an existing longer entitlement.
      v_history_action := null;
      v_entitlement_changed := false;

    else
      v_prior_expiry := v_subscription.expires_at;
      if v_mode = 'rolling_days' then
        v_base := v_now;
        v_expires_at := v_base + pg_catalog.make_interval(days => v_duration);
        v_purchased_start := v_base;
        v_purchased_end := v_expires_at;
      else
        v_expires_at := v_fixed_end;
        v_purchased_start := coalesce(v_payment.provisional_access_started_at, v_now);
        v_purchased_end := v_fixed_end;
      end if;
      v_entitlement_changed := true;
      update public.subscriptions
      set status = 'cancelled', updated_at = v_now, updated_by = p_actor_user_id,
          reason = 'Replaced by approved versioned manual payment.',
          version = version + 1
      where user_id = v_payment.user_id
        and status in ('trialing', 'pending_payment', 'active', 'paused');
      insert into public.subscriptions (
        user_id, plan_code, status, starts_at, expires_at, source,
        created_by, updated_by, reason, pricing_revision_id,
        pricing_plan_version_id, term_duration_days, entitlement_mode
      ) values (
        v_payment.user_id, v_plan.plan_code, 'active',
        case when v_mode = 'fixed_end'
          then coalesce(v_payment.provisional_access_started_at, v_now) else v_now end,
        v_expires_at, 'manual_payment', p_actor_user_id, p_actor_user_id,
        btrim(p_reason), v_plan.revision_id, v_plan.id,
        v_plan.duration_days, v_plan.entitlement_mode
      ) returning * into v_subscription;
      v_history_action := 'activate';
    end if;

    if v_history_action is not null then
      insert into public.subscription_history (
        subscription_id, user_id, actor_user_id, action,
        previous_state, new_state, reason, request_key
      ) values (
        v_subscription.id, v_subscription.user_id, p_actor_user_id,
        v_history_action, v_previous_subscription, to_jsonb(v_subscription),
        btrim(p_reason), left(p_request_key, 96) || '_subscription'
      );
    end if;
  elsif v_status = 'rejected' then
    update public.payment_requests
    set provisional_access_revoked_at = coalesce(provisional_access_revoked_at, v_now)
    where id = v_payment.id;
  end if;

  update public.payment_requests
  set status = v_status,
      reviewed_at = v_now,
      reviewed_by = p_actor_user_id,
      review_reason = btrim(p_reason),
      subscription_id = case when v_status = 'approved' then v_subscription.id else subscription_id end,
      approved_entitlement_starts_at = case when v_status = 'approved' then v_purchased_start else approved_entitlement_starts_at end,
      approved_entitlement_ends_at = case when v_status = 'approved' then v_purchased_end else approved_entitlement_ends_at end,
      approved_prior_expires_at = case when v_status = 'approved' then v_prior_expiry else approved_prior_expires_at end,
      approved_prior_subscription_state = case when v_status = 'approved'
        then v_prior_subscription_snapshot else approved_prior_subscription_state end,
      approved_entitlement_changed = case when v_status = 'approved' then v_entitlement_changed else approved_entitlement_changed end,
      provisional_access_revoked_at = case when v_status = 'rejected'
        then coalesce(provisional_access_revoked_at, v_now) else provisional_access_revoked_at end,
      updated_at = v_now,
      version = version + 1
  where id = v_payment.id returning * into v_payment;

  insert into public.payment_request_history (
    payment_request_id, actor_user_id, action, previous_status, new_status,
    reason, request_key, metadata
  ) values (
    v_payment.id, p_actor_user_id, v_status,
    v_previous_payment->>'status', v_status, btrim(p_reason),
    left(p_request_key, 96) || '_payment',
    jsonb_build_object(
      'pricingRevisionId', v_payment.pricing_revision_id,
      'planVersionId', v_payment.pricing_plan_version_id,
      'subscriptionId', v_subscription.id
    )
  );

  v_result := jsonb_build_object(
    'ok', true,
    'action', 'payment_review',
    'targetUserId', v_payment.user_id,
    'payment', to_jsonb(v_payment) - array[
      'student_note', 'proof_object_path', 'proof_original_name', 'proof_sha256',
      'trusted_payment_account_details'
    ],
    'subscription', case when v_subscription.id is null then null else to_jsonb(v_subscription) end,
    'requestKey', p_request_key,
    'replayed', false
  );
  update public.admin_action_requests
  set result = v_result, completed_at = v_now
  where request_key = p_request_key;
  insert into public.admin_audit_log (
    actor_user_id, action_type, target_user_id, target_resource_type,
    target_resource_id, reason, details
  ) values (
    p_actor_user_id, 'payment_changed', v_payment.user_id,
    'payment_request', v_payment.id::text, btrim(p_reason),
    jsonb_build_object(
      'requestKey', p_request_key,
      'status', v_status,
      'pricingRevisionId', v_payment.pricing_revision_id,
      'planVersionId', v_payment.pricing_plan_version_id
    )
  );
  return v_result;
end;
$$;

create or replace function public.phase4_create_refund_request(
  p_user_id uuid,
  p_payment_request_id uuid,
  p_reason text,
  p_request_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_payment public.payment_requests%rowtype;
  v_subscription public.subscriptions%rowtype;
  v_prior_subscription public.subscriptions%rowtype;
  v_refund public.refund_requests%rowtype;
  v_prior_snapshot jsonb;
  v_start timestamptz;
  v_end timestamptz;
  v_paid numeric(10,2);
  v_total_seconds numeric;
  v_unused_seconds numeric;
  v_suggested numeric(10,2);
  v_can_reverse boolean := false;
  v_access_note text;
begin
  if p_user_id is null or not exists (
    select 1 from auth.users u
    where u.id = p_user_id and coalesce(u.is_anonymous, false) = false
  ) then raise exception 'Authenticated user required'; end if;
  if char_length(btrim(coalesce(p_reason, ''))) not between 10 and 2000
     or p_request_key is null
     or p_request_key !~ '^[A-Za-z0-9_-]{16,128}$' then
    raise exception 'Valid refund reason and request key required';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('refund:' || p_payment_request_id::text, 0)
  );
  select r.* into v_refund
  from public.refund_requests r where r.request_key = p_request_key;
  if v_refund.id is not null then
    if v_refund.user_id <> p_user_id
       or v_refund.payment_request_id <> p_payment_request_id then
      raise exception 'Request key already used';
    end if;
    return jsonb_build_object('id', v_refund.id, 'status', v_refund.status, 'replayed', true);
  end if;
  if exists (
    select 1 from public.refund_requests r
    where r.payment_request_id = p_payment_request_id
      and r.status in ('pending', 'needs_information', 'approved', 'paid')
  ) then raise exception 'A refund request already exists for this payment'; end if;

  select p.* into v_payment
  from public.payment_requests p
  where p.id = p_payment_request_id
    and p.user_id = p_user_id
    and p.status = 'approved'
  for update;
  if v_payment.id is null then raise exception 'Eligible approved payment not found'; end if;
  select s.* into v_subscription
  from public.subscriptions s where s.id = v_payment.subscription_id for update;
  v_prior_snapshot := v_payment.approved_prior_subscription_state;

  if v_payment.approved_entitlement_changed is false then
    -- Stronger unchanged access predates this purchase and must not make a new
    -- payment immediately ineligible for its own seven-day refund window.
    v_start := coalesce(v_payment.reviewed_at, v_payment.submitted_at);
  else
    v_start := coalesce(
      v_payment.approved_entitlement_starts_at,
      v_payment.provisional_access_started_at,
      v_subscription.starts_at,
      v_payment.reviewed_at,
      v_payment.submitted_at
    );
  end if;
  v_end := coalesce(
    v_payment.approved_entitlement_ends_at,
    v_payment.trusted_fixed_ends_at,
    case when v_payment.plan_code = 'early_access_beta'
      then '2026-10-01 23:59:59+08'::timestamptz else null end,
    v_subscription.expires_at
  );
  if (v_now at time zone 'Asia/Manila')::date
       > (v_start at time zone 'Asia/Manila')::date + 6 then
    raise exception 'Refund requests must be filed within seven calendar days of first access';
  end if;

  v_paid := v_payment.trusted_amount_php;
  if v_end is null or v_end <= v_start then
    v_suggested := v_paid;
  else
    v_total_seconds := greatest(1, extract(epoch from (v_end - v_start)));
    v_unused_seconds := greatest(0, extract(epoch from (v_end - v_now)));
    v_suggested := least(v_paid, greatest(0,
      round(v_paid * v_unused_seconds / v_total_seconds, 2)
    ));
  end if;

  -- Reverse only the exact segment recorded by approval. Later renewals or an
  -- unrelated stronger entitlement make automatic shortening unsafe.
  if coalesce(v_payment.approved_entitlement_changed, false)
     and v_subscription.id is not null
     and v_subscription.user_id = p_user_id
     and v_subscription.status in ('trialing', 'pending_payment', 'active', 'paused')
     and not exists (
       select 1
       from public.subscriptions live_subscription
       where live_subscription.user_id = p_user_id
         and live_subscription.status in ('trialing', 'pending_payment', 'active', 'paused')
         and live_subscription.id <> v_subscription.id
     )
     and v_subscription.expires_at is not distinct from v_payment.approved_entitlement_ends_at then
    if v_payment.trusted_entitlement_mode in ('rolling_days', 'fixed_end') then
      -- Prefer exact restoration from the bounded server-created approval
      -- snapshot. This reverses both in-place rolling extensions and fixed-end
      -- replacements without leaving prior entitlement provenance overwritten.
      if v_prior_snapshot is not null
         and v_prior_snapshot->>'snapshotVersion' = '1'
         and v_prior_snapshot->>'subscriptionId' ~ '^[0-9a-f-]{36}$'
         and v_prior_snapshot->>'planCode' ~ '^[a-z][a-z0-9_]{2,63}$'
         and v_prior_snapshot->>'status' in ('trialing', 'pending_payment', 'active', 'paused')
         and v_prior_snapshot->>'source' in ('manual_payment', 'complimentary', 'admin_adjustment', 'migration')
         and coalesce(v_prior_snapshot->>'pricingRevisionId', '') ~ '^([0-9a-f-]{36})?$'
         and coalesce(v_prior_snapshot->>'pricingPlanVersionId', '') ~ '^([0-9a-f-]{36})?$'
         and coalesce(v_prior_snapshot->>'termDurationDays', '') ~ '^([0-9]{1,3})?$'
         and coalesce(v_prior_snapshot->>'entitlementMode', '') ~ '^(fixed_end|rolling_days)?$' then
        select s.* into v_prior_subscription
        from public.subscriptions s
        where s.id::text = v_prior_snapshot->>'subscriptionId'
          and s.user_id = p_user_id
        for update;
      end if;

      if v_prior_subscription.id is not null then
        if v_prior_subscription.id <> v_subscription.id then
          update public.subscriptions
          set status = 'cancelled', updated_at = v_now, updated_by = p_user_id,
              reason = 'Versioned payment refund requested; purchased segment cancelled.',
              version = version + 1
          where id = v_subscription.id;
        end if;
        update public.subscriptions
        set plan_code = v_prior_snapshot->>'planCode',
            status = v_prior_snapshot->>'status',
            starts_at = nullif(v_prior_snapshot->>'startsAt', '')::timestamptz,
            expires_at = nullif(v_prior_snapshot->>'expiresAt', '')::timestamptz,
            source = v_prior_snapshot->>'source',
            pricing_revision_id = nullif(v_prior_snapshot->>'pricingRevisionId', '')::uuid,
            pricing_plan_version_id = nullif(v_prior_snapshot->>'pricingPlanVersionId', '')::uuid,
            term_duration_days = nullif(v_prior_snapshot->>'termDurationDays', '')::integer,
            entitlement_mode = nullif(v_prior_snapshot->>'entitlementMode', ''),
            updated_at = v_now,
            updated_by = p_user_id,
            reason = 'Versioned payment refund requested; exact prior entitlement restored.',
            version = version + 1
        where id = v_prior_subscription.id;
        v_can_reverse := true;
        v_access_note := 'The exact purchased segment was removed and the prior entitlement provenance was restored.';
      elsif v_payment.trusted_entitlement_mode = 'rolling_days'
         and v_payment.approved_prior_expires_at is not null
         and v_payment.approved_prior_expires_at > v_now then
        update public.subscriptions
        set expires_at = v_payment.approved_prior_expires_at,
            updated_at = v_now,
            reason = 'Versioned renewal refund requested; preserved the prior paid expiry.',
            version = version + 1
        where id = v_subscription.id;
        v_can_reverse := true;
        v_access_note := 'The exact renewal segment was removed and the prior paid expiry was preserved.';
      else
        update public.subscriptions
        set status = 'cancelled', updated_at = v_now,
            reason = 'Versioned payment refund requested; access cancellation recorded.',
            version = version + 1
        where id = v_subscription.id;
        v_can_reverse := true;
        v_access_note := 'The exact purchased segment was cancelled pending Founder refund review.';
      end if;
    elsif v_payment.plan_code = 'early_access_beta' then
      v_can_reverse := true;
      update public.subscriptions
      set status = 'cancelled', updated_at = v_now,
          reason = 'Legacy Early Access refund requested; access cancellation recorded.',
          version = version + 1
      where id = v_subscription.id;
      v_access_note := 'Legacy Early Access was cancelled pending Founder refund review.';
    end if;
  end if;
  if not v_can_reverse then
    v_access_note := 'Access was not shortened automatically because the exact purchased segment could not be reversed safely; Founder review is required.';
  end if;

  insert into public.refund_requests (
    user_id, payment_request_id, subscription_id, reason, request_type,
    paid_amount_php, suggested_refund_php, calculation_note, request_key,
    first_access_started_at, cancellation_effective_at, entitlement_ends_at
  ) values (
    p_user_id, v_payment.id, v_payment.subscription_id, btrim(p_reason),
    'student_request', v_paid, v_suggested,
    'Prorated from the immutable purchased term and trusted paid amount. ' || v_access_note,
    p_request_key, v_start, v_now, v_end
  ) returning * into v_refund;

  update public.payment_requests
  set provisional_access_revoked_at = coalesce(provisional_access_revoked_at, v_now),
      updated_at = v_now
  where id = v_payment.id;
  insert into public.refund_request_history (
    refund_request_id, actor_user_id, action, previous_state, new_state,
    reason, request_key
  ) values (
    v_refund.id, p_user_id, 'submitted', '{}'::jsonb,
    jsonb_build_object(
      'status', 'pending',
      'suggestedRefundPhp', v_refund.suggested_refund_php,
      'accessAutomaticallyChanged', v_can_reverse,
      'purchasedStartsAt', v_start,
      'purchasedEndsAt', v_end
    ),
    'Student submitted a versioned plan refund request for administrator review.',
    left(p_request_key, 96) || '_history'
  );
  insert into public.outbound_notifications (
    notification_type, recipient_mailbox, subject, secure_admin_path,
    related_resource_type, related_resource_id
  ) values (
    'refund_submitted', 'premium@duediligence.ph',
    'Due Diligence plan refund review request',
    '/admin/refunds?request=' || v_refund.id::text,
    'refund_request', v_refund.id
  );
  return jsonb_build_object(
    'id', v_refund.id,
    'status', v_refund.status,
    'suggestedRefundPhp', v_refund.suggested_refund_php,
    'calculationNote', v_refund.calculation_note,
    'accessAutomaticallyChanged', v_can_reverse,
    'replayed', false
  );
end;
$$;

