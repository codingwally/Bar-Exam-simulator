-- A due scheduled revision is already effective for public reads. Promote its
-- lifecycle state when a Founder next opens or changes the builder so the
-- one-scheduled-revision invariant remains reusable without a cron job.
create or replace function public.phase4_promote_due_pricing_schedule(
  p_actor_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.phase4_require_founder(p_actor_user_id);
  update public.pricing_revisions r
  set state = 'published',
      published_at = r.effective_at,
      published_by = coalesce(r.updated_by, r.created_by, p_actor_user_id),
      lock_version = r.lock_version + 1,
      updated_at = clock_timestamp(),
      updated_by = coalesce(r.updated_by, p_actor_user_id)
  where r.state = 'scheduled'
    and r.effective_at <= clock_timestamp();
end;
$$;

-- ---------------------------------------------------------------------------
-- Canonical snapshots (the public shape never exposes a private object path)
-- ---------------------------------------------------------------------------

create or replace function public.phase4_pricing_revision_snapshot(
  p_revision_id uuid,
  p_public boolean default false,
  p_at timestamptz default clock_timestamp()
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_revision public.pricing_revisions%rowtype;
  v_plans jsonb := '[]'::jsonb;
  v_methods jsonb := '[]'::jsonb;
begin
  select r.* into v_revision
  from public.pricing_revisions r
  where r.id = p_revision_id;
  if v_revision.id is null then
    return null;
  end if;

  select coalesce(jsonb_agg(method_value order by method_order, method_code), '[]'::jsonb)
  into v_methods
  from (
    select
      c.sort_order as method_order,
      c.channel_code as method_code,
      jsonb_build_object(
        'versionId', c.id,
        'channelCode', c.channel_code,
        'planCode', plan_row.plan_code,
        'label', c.label,
        'accountName', c.account_name,
        'accountDetails', c.account_details,
        'instructions', c.instructions,
        'qrAsset', case when asset_row.id is null then null else jsonb_build_object(
          'assetId', asset_row.id,
          'sha256', asset_row.sha256,
          'mimeType', asset_row.mime_type,
          'width', asset_row.width,
          'height', asset_row.height
        ) end,
        'qrUrl', coalesce(c.qr_public_path, case when c.qr_asset_id is not null
          then '/pricing/assets/' || c.qr_asset_id::text else null end),
        'qrAmountMode', case when c.amount_centavos is null then 'generic' else 'exact' end,
        'qrAmountCentavos', c.amount_centavos,
        'enabled', c.enabled,
        'visible', c.visible,
        'sortOrder', c.sort_order
      ) as method_value
    from public.pricing_payment_channel_versions c
    left join public.pricing_plan_versions plan_row on plan_row.id = c.plan_version_id
    left join public.pricing_assets asset_row on asset_row.id = c.qr_asset_id
    where c.revision_id = v_revision.id
      and (
        not p_public
        or (
          c.enabled and c.visible
          and (c.qr_asset_id is not null or c.qr_public_path is not null)
          and exists (
            select 1
            from public.pricing_plan_versions display_plan
            where display_plan.revision_id = v_revision.id
              and display_plan.visible
              and (display_plan.display_starts_at is null or p_at >= display_plan.display_starts_at)
              and (display_plan.display_ends_at is null or p_at < display_plan.display_ends_at)
              and (c.plan_version_id is null or c.plan_version_id = display_plan.id)
              and (c.amount_centavos is null or c.amount_centavos = display_plan.price_centavos)
          )
        )
      )
  ) method_rows;

  select coalesce(jsonb_agg(plan_value order by plan_order, plan_code), '[]'::jsonb)
  into v_plans
  from (
    select
      plan_row.sort_order as plan_order,
      plan_row.plan_code,
      jsonb_build_object(
        'versionId', plan_row.id,
        'planCode', plan_row.plan_code,
        'name', plan_row.name,
        'badge', plan_row.badge,
        'pricePhp', plan_row.price_centavos / 100.0,
        'priceCentavos', plan_row.price_centavos,
        'currency', plan_row.currency,
        'durationDays', plan_row.duration_days,
        'entitlementMode', plan_row.entitlement_mode,
        'fixedEndsAt', plan_row.fixed_ends_at,
        'fixedEntitlementEndsAt', plan_row.fixed_ends_at,
        'description', plan_row.description,
        'features', plan_row.features,
        'ctaLabel', plan_row.cta_label,
        'renewalNote', plan_row.renewal_note,
        'visible', plan_row.visible,
        'displayStartsAt', plan_row.display_starts_at,
        'displayEndsAt', plan_row.display_ends_at,
        'displayOpen', plan_row.visible
          and (plan_row.display_starts_at is null or p_at >= plan_row.display_starts_at)
          and (plan_row.display_ends_at is null or p_at < plan_row.display_ends_at),
        'checkoutEnabled', plan_row.checkout_enabled,
        'checkoutStartsAt', plan_row.checkout_starts_at,
        'checkoutEndsAt', plan_row.checkout_ends_at,
        'checkoutOpen', plan_row.visible
          and (plan_row.display_starts_at is null or p_at >= plan_row.display_starts_at)
          and (plan_row.display_ends_at is null or p_at < plan_row.display_ends_at)
          and plan_row.checkout_enabled
          and (plan_row.checkout_starts_at is null or p_at >= plan_row.checkout_starts_at)
          and (plan_row.checkout_ends_at is null or p_at < plan_row.checkout_ends_at)
          and exists (
            select 1
            from public.pricing_payment_channel_versions compatible_channel
            where compatible_channel.revision_id = plan_row.revision_id
              and compatible_channel.enabled
              and compatible_channel.visible
              and (compatible_channel.qr_asset_id is not null
                or compatible_channel.qr_public_path is not null)
              and (compatible_channel.plan_version_id is null or compatible_channel.plan_version_id = plan_row.id)
              and (compatible_channel.amount_centavos is null or compatible_channel.amount_centavos = plan_row.price_centavos)
          ),
        'status', case
          when not plan_row.visible
            or (plan_row.display_starts_at is not null and p_at < plan_row.display_starts_at)
            or (plan_row.display_ends_at is not null and p_at >= plan_row.display_ends_at)
            then 'hidden'
          when plan_row.checkout_starts_at is not null and p_at < plan_row.checkout_starts_at
            then 'upcoming'
          when plan_row.checkout_ends_at is not null and p_at >= plan_row.checkout_ends_at
            then case when plan_row.plan_code = 'early_access_beta' then 'legacy' else 'closed' end
          when not plan_row.checkout_enabled then 'unavailable'
          when not exists (
            select 1
            from public.pricing_payment_channel_versions compatible_channel
            where compatible_channel.revision_id = plan_row.revision_id
              and compatible_channel.enabled
              and compatible_channel.visible
              and (compatible_channel.qr_asset_id is not null
                or compatible_channel.qr_public_path is not null)
              and (compatible_channel.plan_version_id is null or compatible_channel.plan_version_id = plan_row.id)
              and (compatible_channel.amount_centavos is null or compatible_channel.amount_centavos = plan_row.price_centavos)
          ) then 'payment_channel_required'
          else 'active'
        end,
        'sortOrder', plan_row.sort_order,
        'promotional', plan_row.promotional,
        'billing', plan_row.billing,
        'paymentMethods', coalesce((
          select jsonb_agg(method_value order by method_order, method_code)
          from (
            select
              compatible_channel.sort_order as method_order,
              compatible_channel.channel_code as method_code,
              jsonb_build_object(
                'versionId', compatible_channel.id,
                'channelCode', compatible_channel.channel_code,
                'planCode', linked_plan.plan_code,
                'label', compatible_channel.label,
                'accountName', compatible_channel.account_name,
                'accountDetails', compatible_channel.account_details,
                'instructions', compatible_channel.instructions,
                'qrAsset', case when linked_asset.id is null then null else jsonb_build_object(
                  'assetId', linked_asset.id,
                  'sha256', linked_asset.sha256,
                  'mimeType', linked_asset.mime_type,
                  'width', linked_asset.width,
                  'height', linked_asset.height
                ) end,
                'qrUrl', coalesce(compatible_channel.qr_public_path,
                  case when compatible_channel.qr_asset_id is not null
                    then '/pricing/assets/' || compatible_channel.qr_asset_id::text else null end),
                'qrAmountMode', case when compatible_channel.amount_centavos is null then 'generic' else 'exact' end,
                'qrAmountCentavos', compatible_channel.amount_centavos,
                'enabled', compatible_channel.enabled,
                'visible', compatible_channel.visible,
                'sortOrder', compatible_channel.sort_order
              ) as method_value
            from public.pricing_payment_channel_versions compatible_channel
            left join public.pricing_plan_versions linked_plan on linked_plan.id = compatible_channel.plan_version_id
            left join public.pricing_assets linked_asset on linked_asset.id = compatible_channel.qr_asset_id
            where compatible_channel.revision_id = plan_row.revision_id
              and (compatible_channel.plan_version_id is null or compatible_channel.plan_version_id = plan_row.id)
              and (compatible_channel.amount_centavos is null or compatible_channel.amount_centavos = plan_row.price_centavos)
              and (not p_public or (
                compatible_channel.enabled and compatible_channel.visible
                and (compatible_channel.qr_asset_id is not null
                  or compatible_channel.qr_public_path is not null)
              ))
          ) compatible_methods
        ), '[]'::jsonb)
      ) as plan_value
    from public.pricing_plan_versions plan_row
    where plan_row.revision_id = v_revision.id
      and (
        not p_public
        or (
          plan_row.visible
          and (plan_row.display_starts_at is null or p_at >= plan_row.display_starts_at)
          and (plan_row.display_ends_at is null or p_at < plan_row.display_ends_at)
        )
      )
  ) plan_rows;

  return jsonb_build_object(
    'revisionId', v_revision.id,
    'revisionNumber', v_revision.revision_number,
    'state', v_revision.state,
    'lockVersion', v_revision.lock_version,
    'schemaVersion', v_revision.schema_version,
    'basedOnRevisionId', v_revision.based_on_revision_id,
    'rollbackOfRevisionId', v_revision.rollback_of_revision_id,
    'effectiveAt', v_revision.effective_at,
    'publishedAt', v_revision.published_at,
    'cancelledAt', v_revision.cancelled_at,
    'createdAt', v_revision.created_at,
    'updatedAt', v_revision.updated_at,
    'contentHash', v_revision.content_hash,
    'serverNow', p_at,
    'timezone', 'Asia/Manila',
    'page', coalesce(v_revision.page_config->'page', '{}'::jsonb),
    'plans', v_plans,
    'paymentMethods', v_methods,
    'faqs', coalesce(v_revision.page_config->'faqs', '[]'::jsonb),
    'config', jsonb_build_object(
      'page', coalesce(v_revision.page_config->'page', '{}'::jsonb),
      'plans', v_plans,
      'paymentMethods', v_methods,
      'faqs', coalesce(v_revision.page_config->'faqs', '[]'::jsonb)
    )
  );
end;
$$;

create or replace function public.phase4_pricing_snapshot()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_revision_id uuid;
begin
  select r.id into v_revision_id
  from public.pricing_revisions r
  where r.state in ('published', 'scheduled')
    and r.effective_at <= v_now
  order by r.effective_at desc, r.revision_number desc
  limit 1;
  if v_revision_id is null then
    return jsonb_build_object(
      'revisionId', null,
      'serverNow', v_now,
      'timezone', 'Asia/Manila',
      'page', '{}'::jsonb,
      'plans', '[]'::jsonb,
      'paymentMethods', '[]'::jsonb,
      'faqs', '[]'::jsonb
    );
  end if;
  return public.phase4_pricing_revision_snapshot(v_revision_id, true, v_now);
end;
$$;

create or replace function public.phase4_admin_pricing_snapshot(p_actor_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_live_id uuid;
  v_draft_id uuid;
  v_scheduled jsonb;
  v_next_scheduled jsonb;
  v_history jsonb;
  v_assets jsonb;
begin
  perform public.phase4_require_founder(p_actor_user_id);
  perform public.phase4_promote_due_pricing_schedule(p_actor_user_id);
  v_now := clock_timestamp();

  select r.id into v_live_id
  from public.pricing_revisions r
  where r.state in ('published', 'scheduled') and r.effective_at <= v_now
  order by r.effective_at desc, r.revision_number desc limit 1;
  select r.id into v_draft_id
  from public.pricing_revisions r where r.state = 'draft'
  order by r.created_at desc limit 1;

  select coalesce(jsonb_agg(
    public.phase4_pricing_revision_snapshot(r.id, false, v_now)
    order by r.effective_at, r.revision_number
  ), '[]'::jsonb)
  into v_scheduled
  from public.pricing_revisions r
  where r.state = 'scheduled' and r.effective_at > v_now;
  v_next_scheduled := v_scheduled->0;

  select coalesce(jsonb_agg(jsonb_build_object(
    'eventId', e.id,
    'revisionId', e.revision_id,
    'eventType', e.event_type,
    'reason', e.reason,
    'metadata', e.metadata,
    'occurredAt', e.occurred_at
  ) order by e.occurred_at desc), '[]'::jsonb)
  into v_history
  from (
    select * from public.pricing_publication_events
    order by occurred_at desc limit 100
  ) e;

  select coalesce(jsonb_agg(jsonb_build_object(
    'assetId', a.id,
    'bucketId', a.bucket_id,
    'objectPath', a.object_path,
    'mimeType', a.mime_type,
    'sizeBytes', a.size_bytes,
    'width', a.width,
    'height', a.height,
    'sha256', a.sha256,
    'createdAt', a.created_at
  ) order by a.created_at desc), '[]'::jsonb)
  into v_assets
  from public.pricing_assets a;

  insert into public.admin_audit_log (
    actor_user_id, action_type, target_resource_type, target_resource_id,
    reason, details
  ) values (
    p_actor_user_id, 'content_management_action', 'pricing_builder',
    coalesce(v_live_id::text, 'none'), 'Authorized pricing builder view.',
    jsonb_build_object('liveRevisionId', v_live_id, 'draftRevisionId', v_draft_id)
  );

  return jsonb_build_object(
    'live', public.phase4_pricing_revision_snapshot(v_live_id, false, v_now),
    'published', public.phase4_pricing_revision_snapshot(v_live_id, false, v_now),
    'draft', public.phase4_pricing_revision_snapshot(v_draft_id, false, v_now),
    'scheduled', v_next_scheduled,
    'scheduledRevisions', v_scheduled,
    'history', v_history,
    'assets', v_assets,
    'serverNow', v_now,
    'timezone', 'Asia/Manila'
  );
end;
$$;

