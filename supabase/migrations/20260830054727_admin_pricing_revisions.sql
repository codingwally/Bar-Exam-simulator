  select value into v_plan
  from jsonb_array_elements(coalesce(v_pricing->'plans', '[]'::jsonb))
  order by case when coalesce((value->>'checkoutOpen')::boolean, false) then 0 else 1 end,
    coalesce((value->>'sortOrder')::integer, 0)
  limit 1;
  select coalesce(bool_or(coalesce((value->>'checkoutOpen')::boolean, false)), false)
  into v_checkout_open
  from jsonb_array_elements(coalesce(v_pricing->'plans', '[]'::jsonb));

  select r.* into v_payment
  from public.payment_requests r
  where r.user_id = p_user_id
    and r.status in ('pending', 'needs_information')
    and r.provisional_access_started_at is not null
    and r.provisional_access_expires_at > clock_timestamp()
    and r.provisional_access_revoked_at is null
  order by r.submitted_at desc limit 1;
  if v_payment.id is not null then
    select p.name into v_plan_name
    from public.pricing_plan_versions p
    where p.id = v_payment.pricing_plan_version_id;
  end if;

  if v_payment.id is not null
     and coalesce((v_access->>'termsRequired')::boolean, true) = false
     and coalesce((v_access->>'reauthenticationRequired')::boolean, false) = false
     and coalesce((v_access->>'profileCompleted')::boolean, false) = true
     and coalesce(v_access->>'basis', '') not in (
       'super_admin', 'founder_admin', 'global_beta_all_access',
       'founding_beta', 'free_beta', 'paid_subscription', 'early_access',
       'provisional_payment'
     ) then
    v_access := v_access || jsonb_build_object(
      'allowed', true,
      'basis', 'provisional_payment',
      'accessMode', 'provisional',
      'accountLabel', coalesce(v_plan_name, 'Paid access') || ' — pending',
      'unlimited', true,
      'paymentRequired', false,
      'paidSubscriptionExpired', false,
      'entitlementEndsAt', v_payment.provisional_access_expires_at,
      'paymentState', v_payment.status
    );
  end if;

  return v_access || jsonb_build_object(
    'checkoutOpen', v_checkout_open,
    'priceCentavos', nullif(v_plan->>'priceCentavos', '')::integer,
    'regularPriceCentavos', nullif(v_plan->>'priceCentavos', '')::integer,
    'salesCloseAt', nullif(v_plan->>'checkoutEndsAt', '')::timestamptz,
    'manualRenewal', true,
    'automaticRenewal', false,
    'pricingRevisionId', v_pricing->>'revisionId',
    'pricing', v_pricing,
    'serverNow', v_pricing->>'serverNow',
    'timezone', 'Asia/Manila'
  );
end;
$$;

