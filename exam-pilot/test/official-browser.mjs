import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const base = process.argv[2] || 'http://localhost:8798';
const evidence = fileURLToPath(new URL('../.wrangler/evidence/', import.meta.url));
await mkdir(evidence, {recursive: true});
const outcomes = [];
const browser = await chromium.launch({headless: true});
async function api(path, data, method = 'POST') {
  const response = await fetch(base + path, {method, headers: {Origin: base, 'Content-Type': 'application/json'}, ...(data ? {body: JSON.stringify(data)} : {})});
  const body = await response.json(); assert.ok(response.ok, JSON.stringify(body)); return body;
}
try {
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}});
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/official`);
  await page.getByRole('heading', {name: 'Test is not available', exact: true}).waitFor();
  assert.equal(await page.locator('textarea').count(), 0);
  await page.screenshot({path: `${evidence}/official-unconfigured.png`});
  outcomes.push('Unconfigured official route displays exact unavailable message; no answer inputs or questions.');
  await api('/api/admin/exams/official/draft', {expected_version: 0, questions: Array.from({length: 20}, (_, index) => ({number: index + 1, text: `Synthetic protected question ${index + 1}\nComplete private fact pattern.`}))}, 'PUT');
  for (const horizon of [172800, 7200, 1200, 360, 240, 30]) {
    const startsAt = Date.now() + horizon * 1000;
    await api('/api/admin/exams/official/schedule', {starts_at: new Date(startsAt).toISOString(), ends_at: new Date(startsAt + 120000).toISOString(), expected_draft_version: 1, confirmed: true, reason: 'Synthetic countdown boundary review'});
    await page.reload(); await page.getByRole('heading', {name: 'Test is not available yet', exact: true}).waitFor();
    const countdown = await page.locator('[data-countdown]').innerText();
    assert.ok(!['', '—', '00:00:00'].includes(countdown), `No immediate countdown at ${horizon}`);
    if (horizon >= 86400) assert.match(countdown, /day/);
    assert.equal(await page.locator('textarea').count(), 0);
    const state = await api('/api/exams/official/state', undefined, 'GET');
    assert.ok(!JSON.stringify(state).includes('Synthetic protected question'));
    if (horizon === 172800) await page.screenshot({path: `${evidence}/official-waiting-days.png`});
    outcomes.push(`Immediate full countdown ${horizon}s early: ${countdown}; no question disclosure.`);
  }
  const startsAt = Date.now() + 12000, endsAt = startsAt + 25000;
  await api('/api/admin/exams/official/schedule', {starts_at: new Date(startsAt).toISOString(), ends_at: new Date(endsAt).toISOString(), expected_draft_version: 1, confirmed: true, reason: 'Synthetic automatic release and cutoff review'});
  await page.reload(); await page.getByRole('button', {name: 'Enter waiting room'}).waitFor();
  await page.getByRole('textbox', {name: 'Full name'}).fill('Synthetic Waiting Student');
  await page.getByRole('textbox', {name: 'Email address'}).fill('waiting@example.invalid');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', {name: 'Enter waiting room'}).click();
  await page.getByText(/You are registered as/).waitFor();
  await page.getByRole('textbox', {name: 'Your answer to question 1', exact: true}).waitFor({timeout: 20000});
  assert.ok(await page.getByText('Synthetic protected question 1', {exact: false}).count());
  await page.getByRole('textbox', {name: 'Your answer to question 1', exact: true}).fill('ON-TIME official answer.');
  await page.getByText(/Saved to server at/).waitFor();
  const onTimeState = await page.evaluate(async () => (await fetch('/api/exams/official/state')).json());
  outcomes.push('Waiting registration automatically unlocks all20 at scheduled start without reloading.');
  const lateContext = await browser.newContext();
  const late = await lateContext.newPage(); await late.goto(`${base}/official`);
  await late.getByRole('textbox', {name: 'Full name'}).fill('Synthetic Late Unlisted Student');
  await late.getByRole('textbox', {name: 'Email address'}).fill('late-unlisted@example.invalid');
  await late.getByRole('checkbox').check(); await late.getByRole('button', {name: 'Begin examination'}).click();
  await late.getByRole('textbox', {name: /Your answer to question/}).waitFor();
  const lateState = await late.evaluate(async () => (await fetch('/api/exams/official/state')).json());
  assert.equal(lateState.attempt.deadlineAt, onTimeState.attempt.deadlineAt);
  outcomes.push('Unlisted late entrant accepted with the same absolute cutoff.');
  await context.setOffline(true);
  await page.getByRole('textbox', {name: 'Your answer to question 1', exact: true}).fill('OFFLINE LATER WRITING must remain separate.');
  while (Date.now() <= endsAt + 700) await new Promise(resolve => setTimeout(resolve, 300));
  await context.setOffline(false);
  await page.reload();
  await page.getByRole('heading', {name: 'Your examination is submitted.'}).waitFor({timeout: 20000});
  await page.getByText(/preserved separately as a late\/offline recovered draft/).waitFor();
  const finalState = await page.evaluate(async () => (await fetch('/api/exams/official/state')).json());
  assert.equal(finalState.attempt.receipt.finalizationType, 'deadline');
  assert.equal(finalState.attempt.answers.find(answer => answer.questionId === onTimeState.attempt.questions[0].id).text, 'ON-TIME official answer.');
  const detail = await api(`/api/admin/attempts/${onTimeState.attempt.id}`, undefined, 'GET');
  assert.ok(detail.recovered_drafts.some(draft => draft.text === 'OFFLINE LATER WRITING must remain separate.'));
  await page.screenshot({path: `${evidence}/official-deadline-receipt.png`, fullPage: true});
  await late.reload(); await late.getByRole('heading', {name: 'Your examination is submitted.'}).waitFor();
  outcomes.push('Offline across cutoff: server freezes last on-time text, issues deadline receipt and separately preserves later offline text.');
  const closedContext = await browser.newContext(); const closed = await closedContext.newPage(); await closed.goto(`${base}/official`);
  await closed.getByRole('heading', {name: 'Examination closed', exact: true}).waitFor();
  assert.equal(await closed.locator('form').count(), 0);
  outcomes.push('After common cutoff, new registrants cannot start; closed-tab attempt retrieves a timed receipt.');
  assert.deepEqual(errors, []);
  await writeFile(`${evidence}/official-results.json`, JSON.stringify({passed: true, outcomes}, null, 2));
  console.log(JSON.stringify({passed: true, outcomes}));
  await Promise.all([context.close(), lateContext.close(), closedContext.close()]);
} finally {await browser.close();}
