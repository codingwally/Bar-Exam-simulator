-- ---------------------------------------------------------------------------
-- Immutable publication ledger guards
-- ---------------------------------------------------------------------------

create or replace function public.phase4_guard_pricing_revision_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'Pricing revisions are append-only';
  end if;
  if old.state = 'draft' then
    return new;
  end if;
  if old.state = 'scheduled' and new.state = 'cancelled'
     and (to_jsonb(new) - array[
       'state','cancelled_at','cancelled_by','updated_at','updated_by','lock_version'
     ]) = (to_jsonb(old) - array[
       'state','cancelled_at','cancelled_by','updated_at','updated_by','lock_version'
     ]) then
    return new;
  end if;
  if old.state = 'scheduled' and new.state = 'published'
     and old.effective_at <= clock_timestamp()
     and (to_jsonb(new) - array[
       'state','published_at','published_by','updated_at','updated_by','lock_version'
     ]) = (to_jsonb(old) - array[
       'state','published_at','published_by','updated_at','updated_by','lock_version'
     ]) then
    return new;
  end if;
  raise exception 'Published or scheduled pricing revisions are immutable';
end;
$$;

create trigger phase4_guard_pricing_revision_mutation_trigger
before update or delete on public.pricing_revisions
for each row execute function public.phase4_guard_pricing_revision_mutation();

create or replace function public.phase4_guard_pricing_child_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_old_state text;
  v_new_state text;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    select r.state into v_old_state
    from public.pricing_revisions r
    where r.id = old.revision_id;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    select r.state into v_new_state
    from public.pricing_revisions r
    where r.id = new.revision_id;
  end if;
  if (tg_op in ('UPDATE', 'DELETE') and v_old_state is distinct from 'draft')
     or (tg_op in ('INSERT', 'UPDATE') and v_new_state is distinct from 'draft') then
    raise exception 'Published or scheduled pricing content is immutable';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create trigger phase4_guard_pricing_plan_versions_trigger
before insert or update or delete on public.pricing_plan_versions
for each row execute function public.phase4_guard_pricing_child_mutation();
create trigger phase4_guard_pricing_payment_channels_trigger
before insert or update or delete on public.pricing_payment_channel_versions
for each row execute function public.phase4_guard_pricing_child_mutation();

