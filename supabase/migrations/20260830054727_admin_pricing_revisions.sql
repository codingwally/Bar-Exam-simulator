  id uuid primary key default gen_random_uuid(),
  revision_number bigint generated by default as identity unique,
  state text not null default 'draft' check (
    state in ('draft', 'scheduled', 'published', 'cancelled')
  ),
  schema_version integer not null default 1 check (schema_version = 1),
  lock_version integer not null default 1 check (lock_version > 0),
  page_config jsonb not null default '{"page":{},"faqs":[]}'::jsonb check (
    jsonb_typeof(page_config) = 'object'
    and jsonb_typeof(coalesce(page_config->'page', '{}'::jsonb)) = 'object'
    and jsonb_typeof(coalesce(page_config->'faqs', '[]'::jsonb)) = 'array'
    and octet_length(page_config::text) <= 131072
  ),
  based_on_revision_id uuid references public.pricing_revisions(id),
  rollback_of_revision_id uuid references public.pricing_revisions(id),
  effective_at timestamptz,
  published_at timestamptz,
  published_by uuid references auth.users(id) on delete set null,
  cancelled_at timestamptz,
  cancelled_by uuid references auth.users(id) on delete set null,
  content_hash text check (content_hash is null or content_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default clock_timestamp(),
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default clock_timestamp(),
  updated_by uuid references auth.users(id) on delete set null,
  check (
    (state = 'draft' and effective_at is null and published_at is null and cancelled_at is null)
    or (state = 'scheduled' and effective_at is not null and published_at is null and cancelled_at is null)
    or (state = 'published' and effective_at is not null and published_at is not null and cancelled_at is null)
    or (state = 'cancelled' and effective_at is not null and cancelled_at is not null)
  )
);

